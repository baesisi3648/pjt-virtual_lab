"""Figure 2 (revision): specialist panel of the representative run and round timeline and per-agent character output of the representative run.

    python -B scripts/revision/make_fig2.py [--avatars reference/revision/figures_v1/avatars] [--out reference/revision/figures_v2/Fig2_v2.png]

Same visual design as the original Figure 2 (avatars reused from it; Arial; mustard round palette). Panel A shows the
role and focus statement generated by the PI agent for the representative run (verbatim). Panel B shows the
round timeline and per-agent character output of the representative run, as in the original figure.
"""
from __future__ import annotations

import argparse
import json
import textwrap
from pathlib import Path

import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt  # noqa: E402
from matplotlib.colors import LinearSegmentedColormap  # noqa: E402
from matplotlib.patches import FancyBboxPatch, Rectangle  # noqa: E402
from PIL import Image  # noqa: E402

ROOT = Path(__file__).resolve().parents[2]
MAIN = ROOT / "experiments" / "runs_rev" / "main_v1"
REP = json.loads((ROOT / "experiments" / "runs_rev" / "results_v1" / "representative.json").read_text(encoding="utf-8"))["representative"]
AVATAR = {"Genetics": "molgen", "Genomics": "molgen", "Risk": "risk", "Bioinformatics": "bioinfo",
          "Toxicology": "tox", "Regulatory": "regsci"}
ORDER = ["Genetics", "Risk", "Bioinformatics", "Toxicology", "Regulatory"]  # same order as the original figure
INK, GRAY, LIGHT = "#1A1A1A", "#4A4A4A", "#8A8A8A"
ROUNDS = LinearSegmentedColormap.from_list("rounds", ["#F6CD7E", "#E2A33A", "#A5650E", "#7A4708"])
plt.rcParams.update({"font.family": "Arial", "font.size": 10})


def mmss(sec: float) -> str:
    s = int(round(sec))
    return f"{s // 60} min {s % 60} s"


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--avatars", default="reference/revision/figures_v1/avatars")
    ap.add_argument("--out", default="reference/revision/figures_v2/Fig2_v2.png")
    a = ap.parse_args()
    team = json.loads((MAIN / REP / "attempt_01" / "team_selection.json").read_text(encoding="utf-8"))["final_team"]
    by = {next(k for k in AVATAR if t["role"].startswith(k)): t for t in team}

    fig = plt.figure(figsize=(15.2, 5.8), dpi=300)
    # ---------- panel A
    axA = fig.add_axes([0.0, 0.0, 0.47, 1.0])
    axA.set_xlim(0, 100); axA.set_ylim(0, 100); axA.axis("off")
    axA.text(1.0, 97, "(A)", fontsize=17, fontweight="bold", va="top", color=INK)
    top, step = 84.5, 17.0
    for i, key in enumerate(ORDER):
        t = by[key if key in by else "Genomics"]
        y = top - i * step
        img = Image.open(Path(ROOT / a.avatars) / f"avatar_{AVATAR[key]}.png")
        h = 14.0  # avatar height in y units; width scaled so the circle stays round
        w = h * (5.8 / 1.0) / (15.2 * 0.47) * (100 / 100)
        axA.imshow(img, extent=(1.6, 1.6 + w, y - 12.6, y - 12.6 + h), zorder=3)
        axA.text(17.0, y + 0.6, t["role"], fontsize=12.5, fontweight="bold", va="center", color=INK)
        lines = textwrap.wrap(t["focus"], 88)
        box_h = 3.3 * len(lines) + 1.6
        axA.add_patch(FancyBboxPatch((16.6, y - 1.9 - box_h), 81.5, box_h, boxstyle="square,pad=0",
                                     fill=False, linestyle=(0, (3, 2)), linewidth=0.9, edgecolor=LIGHT))
        for k, ln in enumerate(lines):
            axA.text(17.6, y - 3.6 - 3.3 * k, ln, fontsize=9.6, va="center", color=INK)
    axA.set_aspect("auto")

    # ---------- panel B (original design: round timeline and per-agent character output of the representative run)
    import csv
    axT = fig.add_axes([0.495, 0.0, 0.5, 1.0]); axT.axis("off"); axT.set_xlim(0, 100); axT.set_ylim(0, 100)
    axT.text(0.5, 97, "(B)", fontsize=17, fontweight="bold", va="top", color=INK)
    axT.text(4.5, 88.5, "Deliberation Execution Profile", fontsize=13, fontweight="bold", color=INK, va="center")
    axT.text(5.0, 80.5, "Round timeline", fontsize=11.5, fontweight="bold", color=INK, va="center")
    meta = json.loads((MAIN / REP / "attempt_01" / "meta.json").read_text(encoding="utf-8"))
    d = [meta["round_durations_seconds"][k] for k in sorted(meta["round_durations_seconds"], key=int)]
    axR = fig.add_axes([0.615, 0.64, 0.355, 0.075])
    x = 0.0
    for k, w in enumerate(d):
        axR.add_patch(Rectangle((x / 60, 0), w / 60, 1, facecolor=ROUNDS(k / 6), edgecolor="white", linewidth=0.8))
        s_ = int(round(w))
        axR.text((x + w / 2) / 60, 0.5, f"R{k + 1} " + f"{s_ // 60}:{s_ % 60:02d}", fontsize=7.6, fontweight="bold", ha="center", va="center", color=INK)
        x += w
    axR.set_xlim(0, 25); axR.set_ylim(0, 1)
    axR.set_yticks([0.5]); axR.set_yticklabels(["Representative run"], fontsize=9.2, color=GRAY)
    axR.set_xticks(range(0, 26, 5)); axR.set_xticklabels([f"{v} min" if v else "0" for v in range(0, 26, 5)], fontsize=8, color=GRAY)
    for sp in ("top", "right", "left"):
        axR.spines[sp].set_visible(False)
    axR.tick_params(axis="y", length=0)
    axR.text(25, -0.95, f"total  {mmss(meta['total_duration_seconds'])}", ha="right", fontsize=9.5, color=GRAY, fontweight="bold")

    axT.text(5.0, 52.5, "Per-agent character output", fontsize=11.5, fontweight="bold", color=INK, va="center")
    stats = {r["agent"]: int(r["chars"]) for r in csv.DictReader((ROOT / "experiments" / "runs_rev" / "results_v1" / "output_stats.csv").open(encoding="utf-8-sig")) if r["run"] == REP}
    rows = [("PI", "PI", "#D64541"), ("Critic", "Critic", "#5D6D7E"), ("Genetics Specialist", "Molecular Genetics", "#A9DCA9"),
            ("Toxicology Specialist", "Toxicology", "#A8E6C8"), ("Regulatory Specialist", "Regulatory Science", "#CDB8EA"),
            ("Risk Specialist", "Risk Assessment", "#F6CFA0"), ("Bioinformatics Specialist", "Bioinformatics", "#82CC9E")]
    axC = fig.add_axes([0.615, 0.08, 0.355, 0.36])
    spec = [stats[k] for k, _, _ in rows[2:]]
    mean = sum(spec) / len(spec)
    for i, (k, lab, col) in enumerate(rows):
        y = len(rows) - 1 - i
        axC.barh(y, stats[k] / 1000, color=col, height=0.66)
        axC.text(stats[k] / 1000 + 1.2, y, f"{stats[k]:,}", va="center", fontsize=8, color=GRAY, fontweight="bold", bbox=dict(facecolor="white", edgecolor="none", pad=0.6))
    axC.axvline(mean / 1000, color=INK, linestyle=(0, (2, 2)), linewidth=0.8)
    axC.text(mean / 1000, len(rows) - 0.25, f"specialist mean ≈ {mean:,.0f}", ha="center", fontsize=8.6, style="italic", color=GRAY)
    axC.set_yticks(range(len(rows))); axC.set_yticklabels([lab for _, lab, _ in rows][::-1], fontsize=9.2, color=INK, fontweight="bold")
    axC.set_xlim(0, 140); axC.set_xlabel("Total characters written (thousands)", color=GRAY, fontsize=9.5)
    for sp in ("top", "right", "left"):
        axC.spines[sp].set_visible(False)
    axC.tick_params(axis="y", length=0); axC.tick_params(axis="x", colors=GRAY, labelsize=8.5)

    out = ROOT / a.out
    out.parent.mkdir(parents=True, exist_ok=True)
    fig.savefig(out, dpi=300, facecolor="white")
    fig.savefig(out.with_suffix(".pdf"), facecolor="white")
    print("wrote", out)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
