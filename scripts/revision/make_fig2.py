"""Figure 2 (revision): specialist panel of the representative run and round timelines of all ten runs.

    python -B scripts/revision/make_fig2.py [--avatars reference/revision/figures_v1/avatars] [--out reference/revision/figures_v1/Fig2_v1.png]

Same visual design as the original Figure 2 (avatars reused from it; Arial; mustard round palette). Panel A shows the
role and focus statement generated by the PI agent for the representative run (verbatim). Panel B replaces the
per-agent character bars with the round timelines of all ten runs, grouped by scoring protocol.
"""
from __future__ import annotations

import argparse
import json
import textwrap
from pathlib import Path

import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt  # noqa: E402
from matplotlib.colors import LinearSegmentedColormap  # noqa: E402
from matplotlib.patches import FancyBboxPatch, Rectangle  # noqa: E402
from PIL import Image  # noqa: E402

ROOT = Path(__file__).resolve().parents[2]
MAIN = ROOT / "experiments" / "runs_rev" / "main_v1"
REP = json.loads((ROOT / "experiments" / "runs_rev" / "results_v1" / "representative.json").read_text(encoding="utf-8"))["representative"]
AVATAR = {"Genetics": "molgen", "Genomics": "molgen", "Risk": "risk", "Bioinformatics": "bioinfo",
          "Toxicology": "tox", "Regulatory": "regsci"}
ORDER = ["Genetics", "Risk", "Bioinformatics", "Toxicology", "Regulatory"]  # same order as the original figure
INK, GRAY, LIGHT = "#1A1A1A", "#4A4A4A", "#8A8A8A"
ROUNDS = LinearSegmentedColormap.from_list("rounds", ["#F6CD7E", "#E2A33A", "#A5650E", "#7A4708"])
plt.rcParams.update({"font.family": "Arial", "font.size": 10})


def mmss(sec: float) -> str:
    s = int(round(sec))
    return f"{s // 60} min {s % 60} s"


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--avatars", default="reference/revision/figures_v1/avatars")
    ap.add_argument("--out", default="reference/revision/figures_v1/Fig2_v1.png")
    a = ap.parse_args()
    team = json.loads((MAIN / REP / "attempt_01" / "team_selection.json").read_text(encoding="utf-8"))["final_team"]
    by = {next(k for k in AVATAR if t["role"].startswith(k)): t for t in team}

    fig = plt.figure(figsize=(15.2, 5.8), dpi=300)
    # ---------- panel A
    axA = fig.add_axes([0.0, 0.0, 0.47, 1.0])
    axA.set_xlim(0, 100); axA.set_ylim(0, 100); axA.axis("off")
    axA.text(1.0, 97, "(A)", fontsize=17, fontweight="bold", va="top", color=INK)
    top, step = 84.5, 17.0
    for i, key in enumerate(ORDER):
        t = by[key if key in by else "Genomics"]
        y = top - i * step
        img = Image.open(Path(ROOT / a.avatars) / f"avatar_{AVATAR[key]}.png")
        h = 14.0  # avatar height in y units; width scaled so the circle stays round
        w = h * (5.8 / 1.0) / (15.2 * 0.47) * (100 / 100)
        axA.imshow(img, extent=(1.6, 1.6 + w, y - 12.6, y - 12.6 + h), zorder=3)
        axA.text(17.0, y + 0.6, t["role"], fontsize=12.5, fontweight="bold", va="center", color=INK)
        lines = textwrap.wrap(t["focus"], 88)
        box_h = 3.3 * len(lines) + 1.6
        axA.add_patch(FancyBboxPatch((16.6, y - 1.9 - box_h), 81.5, box_h, boxstyle="square,pad=0",
                                     fill=False, linestyle=(0, (3, 2)), linewidth=0.9, edgecolor=LIGHT))
        for k, ln in enumerate(lines):
            axA.text(17.6, y - 3.6 - 3.3 * k, ln, fontsize=9.6, va="center", color=INK)
    axA.set_aspect("auto")

    # ---------- panel B
    axT = fig.add_axes([0.495, 0.0, 0.5, 1.0]); axT.axis("off"); axT.set_xlim(0, 100); axT.set_ylim(0, 100)
    axT.text(0.5, 97, "(B)", fontsize=17, fontweight="bold", va="top", color=INK)
    axT.text(4.5, 86.5, "Deliberation Execution Profile", fontsize=13, fontweight="bold", color=INK, va="center")
    axT.text(5.0, 79.5, "Round timeline of every run", fontsize=11.5, fontweight="bold", color=INK, va="center")

    ax = fig.add_axes([0.605, 0.10, 0.355, 0.60])
    runs = [f"A_{i}" for i in range(1, 6)] + [f"B_{i}" for i in range(1, 6)]
    ypos, labels = [], []
    y = 0.0
    for r in runs:
        if r == "B_1":
            y += 0.9
        ypos.append(y); y += 1.0
    ypos = [max(ypos) - v for v in ypos]
    tmax = 0
    for r, yy in zip(runs, ypos):
        meta = json.loads((MAIN / r / "attempt_01" / "meta.json").read_text(encoding="utf-8"))
        d = [meta["round_durations_seconds"][k] / 60 for k in sorted(meta["round_durations_seconds"], key=int)]
        x = 0.0
        for k, w in enumerate(d):
            ax.add_patch(Rectangle((x, yy - 0.36), w, 0.72, facecolor=ROUNDS(k / 6), edgecolor="white", linewidth=0.8))
            if r == REP:
                ax.text(x + w / 2, yy, f"R{k + 1}", fontsize=7.5, fontweight="bold", ha="center", va="center", color=INK)
            x += w
        tot = meta["total_duration_seconds"]
        tmax = max(tmax, x)
        ax.text(x + 0.35, yy, f"{len(d)} rounds, {mmss(tot)}", fontsize=8.6, va="center", color=GRAY,
                fontweight="bold" if r == REP else "normal")
        labels.append(r.replace("_", "") + ("  (representative)" if r == REP else ""))
    ax.set_yticks(ypos); ax.set_yticklabels(labels, fontsize=9.2, color=INK)
    for tl in ax.get_yticklabels():
        if "representative" in tl.get_text():
            tl.set_fontweight("bold")
    ax.set_xlim(0, 30.5); ax.set_ylim(min(ypos) - 0.7, max(ypos) + 1.1)
    ax.set_xticks(range(0, 31, 5)); ax.set_xlabel("Elapsed time (min)", color=GRAY, fontsize=10)
    for s in ("top", "right", "left"):
        ax.spines[s].set_visible(False)
    ax.spines["bottom"].set_color(LIGHT); ax.tick_params(axis="y", length=0); ax.tick_params(axis="x", colors=GRAY, labelsize=9)
    for yy, name in ((ypos[0] + 0.62, "Revised protocol"), (ypos[5] + 0.62, "Comparison protocol")):
        ax.text(0.0, yy, name, fontsize=9.6, fontweight="bold", ha="left", va="bottom", color=INK)
    # round legend
    lx = 0.0
    for k in range(7):
        ax.add_patch(Rectangle((lx + k * 1.55, max(ypos) + 1.55), 1.45, 0.42, facecolor=ROUNDS(k / 6), edgecolor="none", clip_on=False))
        ax.text(lx + k * 1.55 + 0.72, max(ypos) + 1.76, f"R{k + 1}", fontsize=7, ha="center", va="center", color=INK, clip_on=False)
    ax.text(11.3, max(ypos) + 1.76, "deliberation rounds (maximum 7)", fontsize=8.4, va="center", color=GRAY, clip_on=False)

    out = ROOT / a.out
    out.parent.mkdir(parents=True, exist_ok=True)
    fig.savefig(out, dpi=300, facecolor="white")
    fig.savefig(out.with_suffix(".pdf"), facecolor="white")
    print("wrote", out)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
